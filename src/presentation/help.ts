import { RULES } from '../domain/index.ts';

export function helpText(version: string): string {
  return [
    `aggregate-explain ${version}`,
    '',
    'Says why a MongoDB aggregation is slow, in English.',
    '',
    'USAGE',
    '  aggregate-explain [file] [options]',
    '',
    '  Reads explain output from a file, or from stdin when no file is given.',
    '  Any source works — mongosh, the driver, or any version of Mongoose:',
    '',
    "    mongosh --quiet --eval 'JSON.stringify(",
    "      db.orders.explain(\"executionStats\").aggregate(pipeline)",
    "    )' | npx aggregate-explain",
    '',
    'OPTIONS',
    '  --indexes <file>        The collection\'s index list, so index suggestions can',
    '                          rule out duplicating an index you already have:',
    '                            mongosh --quiet --eval \'JSON.stringify({',
    '                              indexes: db.orders.getIndexes(),',
    '                              documentCount: db.orders.estimatedDocumentCount()',
    '                            })\' > indexes.json',
    '  --json                  Machine-readable output',
    '  --min-severity <level>  high | medium | low  (default: low)',
    '  -h, --help              This text',
    '  -V, --version           Version',
    '',
    'EXIT CODES',
    '  0  no findings',
    '  1  findings reported',
    '  2  input could not be read',
    '',
    'CHECKS',
    ...RULES.map((rule) => `  ${rule.id.padEnd(20)}${rule.summary}`),
    '',
  ].join('\n');
}
